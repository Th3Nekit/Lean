/**
 * In-app localization. The Russian string in code is the lookup key; [tr] returns
 * the English translation from [EN] when [lang] == "en", else the Russian
 * passthrough. [lang] is snapshot state (set by LeanTheme from the language
 * setting), so flipping it instantly recomposes every tr(...) reader. Works in
 * non-@Composable helpers too. Interpolated text uses %s/%d templates + .format().
 * Missing keys fall back to Russian, so coverage degrades gracefully.
 */
object I18n {
    var lang by mutableStateOf("ru")

    fun tr(ru: String): String = if (lang == "en") EN[ru] ?: ru else ru
}

fun tr(ru: String): String = I18n.tr(ru)

